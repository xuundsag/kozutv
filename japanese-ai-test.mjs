// Live Japanese audio: MegaPlay English subtitle is automatic, AI Japanese is opt-in.
import {chromium} from 'playwright';
const b=await chromium.launch({headless:true,args:['--no-sandbox','--autoplay-policy=no-user-gesture-required']});
const c=await b.newContext({viewport:{width:1280,height:800}});const p=await c.newPage();const errors=[],reqs=[];
p.on('pageerror',e=>errors.push(String(e)));
p.on('request',r=>{if(r.url().includes('/api/ai-transcription'))try{reqs.push(r.postDataJSON())}catch{}});
await c.addInitScript(()=>{localStorage.setItem('kozutv-autoplay','false');localStorage.setItem('kozutv-save-history','false');localStorage.setItem('kozutv-anime-lang','sub')});
await c.route('**/api/state',r=>r.fulfill({status:200,contentType:'application/json',body:JSON.stringify({history:[],watchlist:[]})}));
await p.goto('http://127.0.0.1:3003/watch/anime/11595?episode=2&lang=sub',{waitUntil:'domcontentloaded',timeout:30000});
await p.waitForFunction(()=>{const v=window.videojs?.getPlayer('kozutv-video');return v?.megaUI&&v.readyState()>=2&&v.duration()>120},{timeout:45000});
const info=await p.evaluate(()=>{const v=videojs.getPlayer('kozutv-video');return {audioLang:v.megaUI&&document.querySelector('.mp-audio-list .selected')?.textContent,subtitle:document.querySelector('.mp-cc-button')?.className}});
await p.evaluate(()=>{const v=videojs.getPlayer('kozutv-video');v.pause();v.currentTime(60);v.megaUI.openSettings('cc')});
await p.waitForTimeout(2500);
const labels=await p.locator('.mp-track-list button').allTextContents();
console.log('labels',JSON.stringify(labels));
await p.evaluate(()=>videojs.getPlayer('kozutv-video').megaUI.openSettings('audio'));
console.log('audio choices',JSON.stringify(await p.locator('.mp-audio-list button').allTextContents()));
await p.evaluate(()=>videojs.getPlayer('kozutv-video').megaUI.openSettings('cc'));
const disclosure=await p.locator('.mp-ai-disclosure').count();
const aiReqBefore=reqs.length;
await p.evaluate(()=>{const v=videojs.getPlayer('kozutv-video');v.pause();v.currentTime(132)});
await p.waitForTimeout(4000);
const aiReqAfterIdle=reqs.length;
const autoCaption=await p.evaluate(()=>document.querySelector('.mp-captions')?.textContent||'');
const prefs=await p.evaluate(()=>JSON.stringify(Object.fromEntries(Object.entries(localStorage).filter(([k])=>k.includes('caption')||k.includes('sub')))));
const netSubs=await p.evaluate(()=>JSON.stringify({tracks:[...document.querySelectorAll('video textTrack')].length,remote:document.querySelector('.mp-track-list')?.innerHTML.slice(0,300)}));
console.log('prefs',prefs);console.log('net',netSubs);
await p.evaluate(()=>videojs.getPlayer('kozutv-video').megaUI.openSettings('cc'));await p.waitForTimeout(400);const jaIndex=0;
const buttons=await p.locator('.mp-track-list button').allTextContents();
await p.locator('[data-track="0"]').click();
await p.waitForTimeout(9000);
const jaReqs=reqs.filter(r=>r.language==='ja');
console.log(JSON.stringify({labels,disclosure,aiCallsWhileIdle:aiReqAfterIdle-aiReqBefore,autoCaption,jaIndex,jaRequestsAfterChoice:jaReqs.length,errors},null,2));
await b.close();
