import assert from 'node:assert/strict';
import {dismissHistory} from '../history-state.js';
import {ANIME_AUDIO_KEYS,REGIONAL_AUDIO_LANGUAGES} from '../audio-languages.js';
import {regionalVariantsFromResolved} from '../ott-resolvers.js';
const row={id:'12',type:'tv',season:1,episode:2,title:'Show',currentTime:1439,duration:1440};
const seed=()=>({history:[{...row}],watchlist:[{...row}]});
let state=seed();dismissHistory(state,{...row,next:{...row,episode:3}});
assert.equal(state.history[0].episode,3);assert.equal(state.history[0].currentTime,0);assert.equal(state.history[0].duration,0);
dismissHistory(state,{...row,next:null});assert.equal(state.history[0].episode,3,'stale tab cannot remove next episode');
state=seed();dismissHistory(state,{...row,next:{...row,season:2,episode:1}});assert.equal(state.history[0].season,2);
state=seed();dismissHistory(state,{...row,next:null});assert.equal(state.history.length,0);assert.equal(state.watchlist.length,1);
for(const next of [{...row},{...row,id:'99',episode:3},{...row,episode:-1},{...row,episode:2.5}])assert.throws(()=>dismissHistory(seed(),{...row,next}));
const movie={...row,type:'movie'};state={history:[movie],watchlist:[movie]};dismissHistory(state,{...movie,completed:true});assert.deepEqual(state,{history:[],watchlist:[]});
state={history:[{...row,type:'anime'}]};dismissHistory(state,{...row,type:'anime',next:{...row,type:'anime',id:'13',episode:1}});assert.equal(state.history[0].id,'13');
for(const code of ['hi','ta','te','ml','bn','mr','gu','pa','ur','zh','yue','fr','ko'])assert(ANIME_AUDIO_KEYS.includes(code));
assert.equal(new Set(ANIME_AUDIO_KEYS).size,ANIME_AUDIO_KEYS.length);
assert(REGIONAL_AUDIO_LANGUAGES.length>40);
const input={type:'tv',id:'123',season:1,episode:1};
const value={url:'https://media.example/master.m3u8',durationSec:1440,sourceKey:'cinesrc',audioStreams:[]};
value.audioStreams=['hi','ta','te','yue','zh'].map(language=>({language,url:value.url,audioLang:language,durationSec:1440}));
assert.deepEqual(regionalVariantsFromResolved(value,input,{originalLanguage:'ja'},1440).map(a=>a.key),['hi','ta','te','yue','zh']);
assert.equal(regionalVariantsFromResolved(value,input,{originalLanguage:'ja'},2700).length,0,'wrong-duration episode rejected');
console.log('PASS atomic history advance, stale dismissal, season/title transitions, movie completion and regional audio contract');
