await cache.get('two',one);await cache.get('one',one);await cache.get('three',one);
assert.equal(cache.stats().entries,2);await cache.get('two',one);assert.equal(loads,4,'LRU evicts least recently used');
time=101;await cache.get('one',one);assert.equal(loads,5,'TTL expires');
let active=0,maxActive=0,failures=0;
const limited=createGenrePageCache({maxEntries:8,maxConcurrent:2,maxPending:20});
await Promise.all(Array.from({length:8},(_,i)=>limited.get(String(i),async()=>{active++;maxActive=Math.max(maxActive,active);await delay(25);active--;return i})));
assert.equal(maxActive,2,'global concurrency is bounded');
await assert.rejects(limited.get('fail',()=>{failures++;throw Error('failure')}));
await delay(0);assert.equal(await limited.get('fail',()=>{failures++;return 'ok'}),'ok');assert.equal(failures,2,'failed result not cached');
await assert.rejects(resolveOttWithFallback({type:'movie',id:'1'},'vidcore',null,{exclude:['vidcore','embedwave','cinesrc','vidlink','vidsrc']}),/No playable stream/);
console.log('PASS cache coalescing, LRU, expiry, concurrency, errors and bounded server exclusions');
const work=fs.mkdtempSync(path.join(os.tmpdir(),'kozu-genre-cache-'));
const excluded=new Set(['states.json','user.json','cache-token.key','cache-tokens.json']);
fs.cpSync(path.join(root,'data'),path.join(work,'data'),{recursive:true,filter:src=>!excluded.has(path.basename(src))&&!src.endsWith('.tmp')});
fs.symlinkSync(path.join(root,'public'),path.join(work,'public'),'dir');
const logPath=path.join(work,'tmdb.log');fs.writeFileSync(logPath,'');
const allocator=net.createServer();await new Promise(r=>allocator.listen(0,'127.0.0.1',r));const port=allocator.address().port;await new Promise(r=>allocator.close(r));
let child=null,logs='';
try{
 child=spawn(process.execPath,['--import',path.join(root,'scripts/fixtures/mock-tmdb.mjs'),path.join(root,'server.js')],{cwd:work,env:{...process.env,PORT:String(port),TMDB_API_KEY:'fixture',TMDB_FIXTURE_LOG:logPath,NVIDIA_API_KEY:'',NVIDIA_API_KEY_FILE:path.join(work,'no-ai-key')},stdio:['ignore','pipe','pipe']});
 child.stdout.on('data',d=>logs+=d);child.stderr.on('data',d=>logs+=d);
 await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('server startup: '+logs)),15000);child.once('exit',c=>{clearTimeout(timer);reject(Error('server exit '+c+': '+logs))});child.stdout.on('data',()=>{if(logs.includes('listening on')){clearTimeout(timer);resolve()}})});
 const base=`http://127.0.0.1:${port}`;
 const req=async url=>{const r=await fetch(base+url);return {status:r.status,data:await r.json()}};
 const page='/api/genre?name=Action&page=1';
 const results=await Promise.all(Array.from({length:16},(_,i)=>req(page+(i%2?'&home=1':''))));
 assert(results.every(r=>r.status===200));
 let lines=()=>fs.readFileSync(logPath,'utf8').trim().split('\n').filter(Boolean);
 assert.equal(lines().length,2,'movie and TV fetched just once for concurrent home/full requests');
 assert(results.find(r=>r.data.hasMore).data.items.length>20);
 const pg2=await req('/api/genre?name=Action&page=2');assert.equal(pg2.status,200);assert.equal(lines().length,4);
 await req('/api/genre?name=Action&page=3');await req('/api/genre?name=Action&page=4');
 assert.equal(lines().length,4,'finished TMDB catalogs are not repeatedly requested during anime tail');
 const fail=await req('/api/genre?name=Comedy&type=movie&page=1');assert.equal(fail.status,502);
 const recovered=await req('/api/genre?name=Comedy&type=movie&page=1');assert.equal(recovered.status,200,'transient catalog failure is not cached as exhaustion');
 const anime=await req('/api/genre?name=Action&type=anime&page=2000');assert.equal(anime.status,200);assert.equal(anime.data.hasMore,false);assert.equal(anime.data.items.length,0);
 const invalid=await req('/api/genre?name=NotAGenre');assert.equal(invalid.status,400);
 console.log('PASS real genre route: shared page cache, no exhausted-upstream requests, error retry and finite tail');
}finally{
 if(child&&child.exitCode===null){const done=once(child,'exit').catch(()=>{});child.kill('SIGTERM');await Promise.race([done,delay(2000)]);if(child.exitCode===null)child.kill('SIGKILL')}
 fs.rmSync(work,{recursive:true,force:true});
}
