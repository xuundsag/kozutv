import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {fileURLToPath} from 'node:url';
import {createGenrePageCache} from '../genre-page-cache.js';
import {resolveOttWithFallback} from '../ott-resolvers.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
let time=0,loads=0;
const cache=createGenrePageCache({ttlMs:100,maxEntries:2,maxConcurrent:2,now:()=>time});
const delay=ms=>new Promise(r=>setTimeout(r,ms));
const one=()=>{loads++;return delay(30).then(()=>({v:loads}))};
const burst=await Promise.all(Array.from({length:12},()=>cache.get('one',one)));
